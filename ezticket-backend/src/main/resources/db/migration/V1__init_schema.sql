-- 1. BẢNG USERS (Tài khoản người dùng & Quản trị viên)
CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       full_name VARCHAR(100) NOT NULL,
                       email VARCHAR(255) NOT NULL UNIQUE,
                       password_hash VARCHAR(255) NOT NULL,
                       phone VARCHAR(20),
                       address VARCHAR(255),
                       role VARCHAR(20) NOT NULL DEFAULT 'USER',
                       status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
                       created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
                       updated_at TIMESTAMP WITHOUT TIME ZONE,
                       CONSTRAINT chk_users_role CHECK (role IN ('USER', 'ADMIN')),
                       CONSTRAINT chk_users_status CHECK (status IN ('ACTIVE', 'LOCKED'))
);

-- 2. BẢNG CATEGORIES (Danh mục sự kiện)
CREATE TABLE categories (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name VARCHAR(100) NOT NULL UNIQUE,
                            slug VARCHAR(150) NOT NULL UNIQUE,
                            description TEXT,
                            created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
                            updated_at TIMESTAMP WITHOUT TIME ZONE
);

-- 3. BẢNG EVENTS (Sản phẩm sự kiện)
CREATE TABLE events (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        category_id BIGINT NOT NULL,
                        title VARCHAR(255) NOT NULL,
                        slug VARCHAR(300) NOT NULL UNIQUE,
                        description TEXT,
                        banner_url VARCHAR(500),
                        venue VARCHAR(255) NOT NULL,
                        city VARCHAR(100),
                        start_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                        end_time TIMESTAMP WITHOUT TIME ZONE,
                        status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
                        created_by BIGINT,
                        created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
                        updated_at TIMESTAMP WITHOUT TIME ZONE,
                        CONSTRAINT fk_events_categories FOREIGN KEY (category_id) REFERENCES categories (id),
                        CONSTRAINT fk_events_users FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
                        CONSTRAINT chk_events_time CHECK (end_time IS NULL OR end_time >= start_time),
                        CONSTRAINT chk_events_status CHECK (status IN ('DRAFT', 'OPEN', 'CLOSED', 'ENDED'))
);

-- 4. BẢNG TICKET_TYPES (Các hạng vé của sự kiện)
CREATE TABLE ticket_types (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              event_id BIGINT NOT NULL,
                              name VARCHAR(100) NOT NULL,
                              price DECIMAL(12, 2) NOT NULL,
                              total_quantity INTEGER NOT NULL,
                              sold_quantity INTEGER NOT NULL DEFAULT 0,
                              max_per_order INTEGER DEFAULT 4,
                              status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
                              created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
                              updated_at TIMESTAMP WITHOUT TIME ZONE,
                              CONSTRAINT fk_ticket_types_events FOREIGN KEY (event_id) REFERENCES events (id),
                              CONSTRAINT uq_ticket_types_event_name UNIQUE (event_id, name),
                              CONSTRAINT chk_ticket_types_price CHECK (price >= 0),
                              CONSTRAINT chk_ticket_types_total_qty CHECK (total_quantity > 0),
                              CONSTRAINT chk_ticket_types_sold_qty CHECK (sold_quantity >= 0 AND sold_quantity <= total_quantity),
                              CONSTRAINT chk_ticket_types_max_order CHECK (max_per_order IS NULL OR max_per_order > 0),
                              CONSTRAINT chk_ticket_types_status CHECK (status IN ('OPEN', 'SOLD_OUT', 'CLOSED'))
);

-- 5. BẢNG ORDERS (Đơn hàng & Giữ chỗ tạm thời 10 phút)
CREATE TABLE orders (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        order_code VARCHAR(50) NOT NULL UNIQUE,
                        total_amount DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
                        status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
                        payment_method VARCHAR(30),
                        payment_ref VARCHAR(100) UNIQUE,
                        hold_expires_at TIMESTAMP WITHOUT TIME ZONE,
                        paid_at TIMESTAMP WITHOUT TIME ZONE,
                        created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
                        updated_at TIMESTAMP WITHOUT TIME ZONE,
                        CONSTRAINT fk_orders_users FOREIGN KEY (user_id) REFERENCES users (id),
                        CONSTRAINT chk_orders_total_amount CHECK (total_amount >= 0),
                        CONSTRAINT chk_orders_status CHECK (status IN ('PENDING', 'HOLDING', 'PAID', 'CANCELLED', 'EXPIRED'))
);

-- 6. BẢNG ORDER_ITEMS (Chi tiết từng hạng vé trong đơn hàng)
CREATE TABLE order_items (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             order_id BIGINT NOT NULL,
                             ticket_type_id BIGINT NOT NULL,
                             quantity INTEGER NOT NULL,
                             unit_price DECIMAL(12, 2) NOT NULL,
                             subtotal DECIMAL(14, 2) NOT NULL,
                             created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
                             CONSTRAINT fk_order_items_orders FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
                             CONSTRAINT fk_order_items_ticket_types FOREIGN KEY (ticket_type_id) REFERENCES ticket_types (id),
                             CONSTRAINT chk_order_items_qty CHECK (quantity > 0)
);

-- 7. BẢNG TICKETS (Vé điện tử định danh & QR HMAC-SHA256)
CREATE TABLE tickets (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         ticket_code VARCHAR(100) NOT NULL UNIQUE,
                         order_id BIGINT NOT NULL,
                         order_item_id BIGINT,
                         ticket_type_id BIGINT NOT NULL,
                         user_id BIGINT NOT NULL,
                         event_id BIGINT NOT NULL,
                         holder_name VARCHAR(100),
                         qr_payload TEXT NOT NULL,
                         qr_signature VARCHAR(256) NOT NULL,
                         pdf_url VARCHAR(500),
                         status VARCHAR(20) NOT NULL DEFAULT 'VALID',
                         checked_in_at TIMESTAMP WITHOUT TIME ZONE,
                         created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
                         CONSTRAINT fk_tickets_orders FOREIGN KEY (order_id) REFERENCES orders (id),
                         CONSTRAINT fk_tickets_order_items FOREIGN KEY (order_item_id) REFERENCES order_items (id) ON DELETE SET NULL,
                         CONSTRAINT fk_tickets_ticket_types FOREIGN KEY (ticket_type_id) REFERENCES ticket_types (id),
                         CONSTRAINT fk_tickets_users FOREIGN KEY (user_id) REFERENCES users (id),
                         CONSTRAINT fk_tickets_events FOREIGN KEY (event_id) REFERENCES events (id),
                         CONSTRAINT chk_tickets_status CHECK (status IN ('VALID', 'USED', 'EXPIRED', 'CANCELLED'))
);

-- ==========================================================
-- INDEXES (Tối ưu hóa hiệu năng truy vấn và tìm kiếm)
-- ==========================================================
CREATE INDEX idx_events_category ON events(category_id);
CREATE INDEX idx_events_status ON events(status);
CREATE INDEX idx_ticket_types_event ON ticket_types(event_id);
CREATE INDEX idx_orders_user ON orders(user_id);
CREATE INDEX idx_orders_status ON orders(status);
CREATE INDEX idx_tickets_user ON tickets(user_id);
CREATE INDEX idx_tickets_event ON tickets(event_id);
CREATE INDEX idx_tickets_code ON tickets(ticket_code);